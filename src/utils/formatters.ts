import type { Conversation, DateCategory } from '../types/chat';

export function formatDateGroup(timestamp: number): DateCategory {
  const now = new Date();
  const date = new Date(timestamp);

  // Strip hours/mins for day difference
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const target = new Date(date.getFullYear(), date.getMonth(), date.getDate());

  const diffTime = today.getTime() - target.getTime();
  const diffDays = Math.floor(diffTime / (1000 * 60 * 60 * 24));

  if (diffDays === 0) return 'Today';
  if (diffDays === 1) return 'Yesterday';
  if (diffDays <= 7) return 'Previous 7 Days';
  if (diffDays <= 30) return 'Previous 30 Days';
  return 'Older';
}

export function formatTime(timestamp: number): string {
  if (!timestamp) return '';
  const date = new Date(timestamp);
  return date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
}

export function formatBytes(bytes: number, decimals: number = 1): string {
  if (!bytes || bytes === 0) return '0 B';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['B', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(dm))} ${sizes[i]}`;
}

export function exportConversationToMarkdown(conversation: Conversation): void {
  const dateStr = new Date(conversation.createdAt).toLocaleString();
  let markdown = `# ${conversation.title}\n\n`;
  markdown += `**Date:** ${dateStr}  \n`;
  markdown += `**Model:** ${conversation.model}  \n`;
  markdown += `**Generated by:** Personal AI (Cybersecurity Assistant)  \n\n`;
  markdown += `---\n\n`;

  conversation.messages.forEach((msg) => {
    const roleName = msg.role === 'user' ? '👤 Muhammad Salman A.' : '🛡️ Personal AI';
    const time = msg.timestamp ? ` *(${new Date(msg.timestamp).toLocaleTimeString()})*` : '';
    markdown += `### ${roleName}${time}\n\n`;
    markdown += `${msg.content}\n\n`;
    markdown += `---\n\n`;
  });

  const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  const cleanTitle = conversation.title.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 40) || 'chat';
  link.download = `personal-ai-${cleanTitle}-${Date.now()}.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
